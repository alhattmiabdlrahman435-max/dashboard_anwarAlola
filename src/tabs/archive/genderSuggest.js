/** أسماء تُستخدم للجنسين — لا نقترح لها شيئاً (تُترك للمستخدم) */
const UNISEX = list('نور جهاد صباح عطاء رجاء وئام ضياء يسري جود ريان وسام اصيل شمس ابرار انوار الطاف نسيم ايان اكنان');

/** أسماء ذكور تنتهي بـ ة أو اء (استثناء من قاعدة الإناث) */
const MALE_ENDINGS_EXCEPT = list('حمزة اسامة طلحة عبيدة حذيفة عروة معاوية عكرمة قتادة ميسرة علاء بهاء زكرياء اسامه حمزه خليفة عطية براء');

export function suggestGender(fullName) {
  const parts = norm(fullName).split(/\s+/).filter(Boolean);
  if (!parts.length) return null;
  // «عبد الله» مكتوبة منفصلة
  const first = parts[0] === 'عبد' && parts[1] ? `عبد${parts[1]}` : parts[0];

  if (UNISEX.has(first)) return null;
  if (first.startsWith('عبد') || first.startsWith('ابو')) return 'male';
  if (MALE.has(first) || MALE_ENDINGS_EXCEPT.has(first)) return 'male';
  if (FEMALE.has(first)) return 'female';
  // القاعدة العامة: المنتهي بتاء مربوطة أو «اء» أنثى غالباً
  if (/(ة|ه)$/.test(first) && first.length > 2) return 'female';
  if (/اء$/.test(first)) return 'female';
  return null; // غير متأكد → يُترك للمستخدم
}
